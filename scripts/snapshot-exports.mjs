// Regenerates src/lib/templates/package-exports.json: the export names (values and types) of the
// libraries generated projects may import. Used to catch `import { Instagram } from "lucide-react"`
// style mistakes before a build. Run after changing ALLOWED_LIBRARIES:  node scripts/snapshot-exports.mjs
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const librariesSource = readFileSync(join(root, "src/lib/templates/libraries.ts"), "utf8");
const range = (name) => {
  const match = librariesSource.match(new RegExp(`"?${name}"?: "([^"]+)"`));
  if (!match) throw new Error(`${name} not found in libraries.ts`);
  return match[1];
};

const packages = ["lucide-react", "recharts", "react-router-dom", "date-fns", "zustand"];
const dir = mkdtempSync(join(tmpdir(), "exports-"));
const dependencies = Object.fromEntries(packages.map((name) => [name, range(name)]));
Object.assign(dependencies, { react: "^19.3.0", "react-dom": "^19.3.0", "@types/react": "^19.3.0", "@types/react-dom": "^19.3.0" });
writeFileSync(join(dir, "package.json"), JSON.stringify({ name: "snap", private: true, dependencies }));
execFileSync("npm", ["install", "--no-audit", "--no-fund", "--silent"], { cwd: dir, stdio: "inherit" });

const ts = createRequire(join(root, "package.json"))("typescript");
const entry = join(dir, "entry.ts");
writeFileSync(entry, [...packages, "react"].map((name, i) => `import * as m${i} from "${name}"; void m${i};`).join("\n"));
const program = ts.createProgram([entry], {
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  module: ts.ModuleKind.ESNext,
  target: ts.ScriptTarget.ES2022,
  skipLibCheck: true,
  jsx: ts.JsxEmit.ReactJSX,
  types: [],
});
const checker = program.getTypeChecker();
const result = { _comment: "Generated by scripts/snapshot-exports.mjs. Do not edit by hand.", versions: {} };
for (const name of [...packages, "react"]) {
  const source = program.getSourceFile(entry);
  const importDecl = source.statements.find((s) => s.moduleSpecifier?.text === name);
  const moduleSymbol = checker.getSymbolAtLocation(importDecl.moduleSpecifier);
  result[name] = checker.getExportsOfModule(moduleSymbol).map((symbol) => symbol.getName()).filter((n) => n !== "default").sort();
  result.versions[name] = JSON.parse(readFileSync(join(dir, "node_modules", name, "package.json"), "utf8")).version;
  console.log(name, result.versions[name], result[name].length);
}
writeFileSync(join(root, "src/lib/templates/package-exports.json"), JSON.stringify(result) + "\n");
