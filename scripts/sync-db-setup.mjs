import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
const files = readdirSync("drizzle")
  .filter((f) => /^\d.*\.sql$/.test(f))
  .sort();
const sql = files
  .map((f) => `-- ${f}\n${readFileSync(`drizzle/${f}`, "utf8").replaceAll("--> statement-breakpoint", "")}`)
  .join("\n");
const journal = JSON.parse(readFileSync("drizzle/meta/_journal.json", "utf8"));
const tracking = journal.entries
  .map((entry) => {
    const hash = createHash("sha256")
      .update(readFileSync(`drizzle/${entry.tag}.sql`))
      .digest("hex");
    return `INSERT INTO drizzle.__drizzle_migrations(hash,created_at) VALUES('${hash}',${entry.when});`;
  })
  .join("\n");
writeFileSync(
  "drizzle/all-in-one.sql",
  `-- Idea2App AI: full setup through ${files.at(-1)}. Generated by scripts/sync-db-setup.mjs.
-- Run once on an EMPTY database. Existing installations must apply only missing migrations.
DO $setup$
BEGIN
  IF to_regclass('public.users') IS NOT NULL THEN
    RAISE EXCEPTION 'Tables already exist; apply only missing migrations.';
  END IF;
${sql}
CREATE SCHEMA IF NOT EXISTS drizzle;
CREATE TABLE IF NOT EXISTS drizzle.__drizzle_migrations(id serial primary key,hash text not null,created_at bigint);
${tracking}
END
$setup$;
`,
);
